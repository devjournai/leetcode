/**
 * Minimum Generations to Target Point
 * Intuition: Midpoint floor((a+b)/2) preserves values whose bits eventually match the target. Each coordinate is independent: k is the max over axes of the steps to produce target[c] from the set of points.
 * Approach: 1. For each coordinate, BFS/set-closure with midpoint until target appears or the set stabilizes (bounded by min..max). 2. Return max k over coords, or -1 if any coord is impossible. Combined 3D: actually generations mix all coords together from same pairs, so simulate sets of 3D points with a generation counter, but the closure is huge. Per-coordinate independent because midpoint is componentwise, and pairing is the same pair of points. If target is in the integer lattice generated by repeated floor-mid from the initial set, k is the min t such that target is in gen t. Simulate per-coordinate independently then take max, because a pair used for x is the same pair for y,z so generations must align. Safer: work with bit differences. For each axis, numbers can only decrease toward convex combinations. If target is outside [min,max] on any axis return -1. Then BFS on the tuple of values along one axis.
 * Dry Run: Input: points = [[0,0,0],[6,6,6]], target = [3,3,3]. Output: 1.
 * Time Complexity: O(G * P^2)
 * Space Complexity: O(P)
 */
var minGenerations = function (points, target) {
  const key = (p) => p.join(",");
  const seen = new Set(points.map(key));
  if (seen.has(key(target))) return 0;
  let gen = points.map((p) => p.slice());
  for (let k = 1; k <= 40; k++) {
    const nxt = [];
    const all = gen;
    for (let i = 0; i < all.length; i++) {
      for (let j = i + 1; j < all.length; j++) {
        const c = [
          Math.floor((all[i][0] + all[j][0]) / 2),
          Math.floor((all[i][1] + all[j][1]) / 2),
          Math.floor((all[i][2] + all[j][2]) / 2),
        ];
        const kk = key(c);
        if (!seen.has(kk)) {
          seen.add(kk);
          nxt.push(c);
          if (kk === key(target)) return k;
        }
      }
    }
    if (!nxt.length) break;
    gen = gen.concat(nxt);
    if (gen.length > 4000) break;
  }
  return -1;
};
