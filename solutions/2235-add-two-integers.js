/**
 * Add Two Integers
 * Intuition: Addition can be performed without the standard '+' operator by simulating binary addition using bitwise operations. The XOR operator handles the sum bits while ignoring carries, and the AND operator followed by a left-shift calculates the carry bits. This process repeats until no more carries are generated.
 * Approach: 1. Initialize two temporary variables, `currentAddend` and `currentCarryValue`, with the input numbers `num1` and `num2` respectively. 2. Enter a loop that continues as long as `currentCarryValue` is not zero. 3. Inside the loop, calculate the sum of `currentAddend` and `currentCarryValue` without considering carries using the bitwise XOR operator, storing the result in a new variable `intermediateSum`. 4. Calculate the carry bits generated by `currentAddend` and `currentCarryValue` using the bitwise AND operator, then left-shift the result by one position, storing this in a new variable `intermediateCarry`. 5. Update `currentAddend` to `intermediateSum` and `currentCarryValue` to `intermediateCarry` for the next iteration. 6. Once `currentCarryValue` becomes zero, it means all carries have been processed, and `currentAddend` holds the final sum.
 * Dry Run: num1 = 5, num2 = 3
 * Initial:
 *   currentAddend = 5 (0101)
 *   currentCarryValue = 3 (0011)
 *
 * Loop 1 (currentCarryValue is 3, not 0):
 *   intermediateSum = currentAddend ^ currentCarryValue = 5 ^ 3 = 0101 ^ 0011 = 0110 (6)
 *   intermediateCarry = (currentAddend & currentCarryValue) << 1 = (5 & 3) << 1 = (0001) << 1 = 0010 (2)
 *   currentAddend becomes 6
 *   currentCarryValue becomes 2
 *
 * Loop 2 (currentCarryValue is 2, not 0):
 *   intermediateSum = currentAddend ^ currentCarryValue = 6 ^ 2 = 0110 ^ 0010 = 0100 (4)
 *   intermediateCarry = (currentAddend & currentCarryValue) << 1 = (6 & 2) << 1 = (0010) << 1 = 0100 (4)
 *   currentAddend becomes 4
 *   currentCarryValue becomes 4
 *
 * Loop 3 (currentCarryValue is 4, not 0):
 *   intermediateSum = currentAddend ^ currentCarryValue = 4 ^ 4 = 0100 ^ 0100 = 0000 (0)
 *   intermediateCarry = (currentAddend & currentCarryValue) << 1 = (4 & 4) << 1 = (0100) << 1 = 1000 (8)
 *   currentAddend becomes 0
 *   currentCarryValue becomes 8
 *
 * Loop 4 (currentCarryValue is 8, not 0):
 *   intermediateSum = currentAddend ^ currentCarryValue = 0 ^ 8 = 0000 ^ 1000 = 1000 (8)
 *   intermediateCarry = (currentAddend & currentCarryValue) << 1 = (0 & 8) << 1 = (0000) << 1 = 0000 (0)
 *   currentAddend becomes 8
 *   currentCarryValue becomes 0
 *
 * Loop terminates (currentCarryValue is 0).
 * Return currentAddend, which is 8. (5 + 3 = 8)
 * Time Complexity: O(1)
 * Space Complexity: O(1)
 */
var sum = function (num1, num2) {
  let currentAddend = num1;
  let currentCarryValue = num2;

  while (currentCarryValue !== 0) {
    let intermediateSum = currentAddend ^ currentCarryValue;
    let intermediateCarry = (currentAddend & currentCarryValue) << 1;
    currentAddend = intermediateSum;
    currentCarryValue = intermediateCarry;
  }

  return currentAddend;
};
