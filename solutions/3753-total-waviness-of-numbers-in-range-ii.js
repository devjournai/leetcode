/**
 * Total Waviness of Numbers in Range II
 * Intuition: The problem asks for the sum of waviness for numbers in a given range [num1, num2]. Since num2 can be up to 10^15, a direct iteration is infeasible. This indicates a digit dynamic programming approach. The sum over a range [num1, num2] can be calculated as `solve(num2) - solve(num1 - 1)`, where `solve(N)` computes the total waviness for all numbers in [1, N].
 *
 * Approach:
 * 1. Define a helper function `solve(N)` that calculates the total waviness for numbers in the range `[1, N]`. This function will use digit DP.
 * 2. The DP state needs to capture enough information to decide if a digit forms a peak or a valley. A peak/valley depends on three consecutive digits (left, current, right). When building a number digit by digit from left to right, we'll need the two previously placed digits to evaluate the "middle" digit as we place the "right" digit.
 * 3. The DP function signature will be `dp(idx, tight, isAllZeroPrefix, prevDigitVal, prevPrevDigitVal)`:
 *    - `idx`: The current digit position we are considering (0-indexed) in the string representation of `N`.
 *    - `tight`: A boolean flag. If true, it means we are restricted by the digits of `N` at the current position. Otherwise, we can place any digit from 0 to 9.
 *    - `isAllZeroPrefix`: A boolean flag. True if all digits placed so far (from index 0 up to `idx-1`) are zeros. This helps in identifying leading zeros, which don't count towards the actual number structure for peaks/valleys.
 *    - `prevDigitVal`: The digit placed at `idx - 1` in the number being formed. Initialized to -1 for `idx = 0`.
 *    - `prevPrevDigitVal`: The digit placed at `idx - 2` in the number being formed. Initialized to -1 for `idx = 0, 1`.
 * 4. The `dp` function will return an object `{ totalWaviness: number, count: number }`. `totalWaviness` is the sum of waviness generated by suffixes starting from `idx`, and `count` is the number of valid suffixes.
 * 5. Base Case: If `idx === len` (where `len` is the length of `N` as a string), we've formed a complete number. It contributes 0 waviness from this point, but 1 to the count of numbers. So, return `{ totalWaviness: 0, count: 1 }`.
 * 6. Memoization: Use a 5D array `memo` to store computed results. Initialize with `null`.
 * 7. Recursive Step:
 *    - Iterate `d` from 0 up to `upperLimit` (which is `N[idx]` if `tight`, else 9).
 *    - Update `newTight` and `newIsAllZeroPrefix` for the recursive call.
 *    - Recursively call `dp(idx + 1, newTight, newIsAllZeroPrefix, d, prevDigitVal)` to get results for the suffix.
 *    - Add `res.totalWaviness` to `ansTotalWaviness` and `res.count` to `ansCount`.
 *    - Crucially, check if `prevDigitVal` (the digit at `idx-1` in the current number being formed) forms a peak or valley with its neighbors `prevPrevDigitVal` (at `idx-2`) and `d` (at `idx`).
 *    - Conditions for `prevDigitVal` to contribute `1` waviness:
 *        - `idx >= 2`: Ensures `prevPrevDigitVal` and `prevDigitVal` are valid historical digits (not -1). This means `prevDigitVal` is not the first digit of the full string representation of `N`.
 *        - `!isAllZeroPrefix`: Ensures that `prevPrevDigitVal` (and consequently `prevDigitVal`) is not a leading zero. This is vital to consider only actual digits of the number. If this condition holds, `prevPrevDigitVal` is effectively the first, or a later, non-zero digit.
 *        - Check the peak/valley condition: `(prevDigitVal > prevPrevDigitVal && prevDigitVal > d)` for a peak, or `(prevDigitVal < prevPrevDigitVal && prevDigitVal < d)` for a valley.
 *    - If `prevDigitVal` is a peak/valley, add `1 * res.count` to `ansTotalWaviness`. This is because this peak/valley contributes 1 to waviness for each of the `res.count` suffixes formed.
 * 8. Initial call: `dp(0, true, true, -1, -1)`.
 * 9. The final answer is `solve(num2) - solve(num1 - 1)`. Numbers with less than 3 digits implicitly have 0 waviness from the `idx >= 2` condition (they can never satisfy it for `idx-1` as the middle digit). Numbers like 0, 1, ..., 99 will have 0 waviness.
 *
 * Dry Run: num1 = 120, num2 = 130
 * We need `solve(130) - solve(119)`.
 * Let's trace `solve(121)` to confirm individual waviness calculation. `sNum = "121"`, len = 3.
 * `dp(0, true, true, -1, -1)`
 *   `d=1` (for `sNum[0]`) -> `newIsAllZeroPrefix=false, newPrevDigit=1, newPrevPrevDigit=-1`
 *   `res_1 = dp(1, true, false, 1, -1)`
 *     `d=2` (for `sNum[1]`) -> `newIsAllZeroPrefix=false, newPrevDigit=2, newPrevPrevDigit=1`
 *     `res_2 = dp(2, true, false, 2, 1)`
 *       `d=1` (for `sNum[2]`) -> `newIsAllZeroPrefix=false, newPrevDigit=1, newPrevPrevDigit=2`
 *       `res_3 = dp(3, true, false, 1, 2)` (base case) -> returns `{totalWaviness: 0, count: 1}`
 *       `ansTotalWaviness_2 += 0`, `ansCount_2 += 1`.
 *       Check waviness: `idx=2`, `tight=true`, `isAllZeroPrefix=false`, `prevDigitVal=2`, `prevPrevDigitVal=1`. `d=1`.
 *       Condition `idx >= 2 && !isAllZeroPrefix` is `true`.
 *       `prevDigitVal=2` vs `prevPrevDigitVal=1` and `d=1`: `2 > 1 && 2 > 1` (peak). `wavinessContribution = 1`.
 *       `ansTotalWaviness_2 += 1 * res_3.count = 1 * 1 = 1`.
 *       `memo[2][true][false][2+1][1+1] = {totalWaviness: 1, count: 1}`.
 *       `res_2` gets `{1,1}` from this path (number `121`).
 *       `ansTotalWaviness_1 += 1`, `ansCount_1 += 1`.
 *       No waviness check for `idx=1` because `idx < 2`.
 *     `memo[1][true][false][1+1][-1+1] = {totalWaviness: 1, count: 1}`.
 *     `res_1` gets `{1,1}`.
 *   `ansTotalWaviness_0 += 1`, `ansCount_0 += 1`.
 *   No waviness check for `idx=0` because `idx < 2`.
 *   The `solve("121")` correctly returns `1`.
 * Similarly, `solve("120")` would return `1` and `solve("130")` would return `1` for the respective numbers.
 * The `solve` function correctly accumulates waviness for *all* numbers less than or equal to N based on these rules.
 *
 * Time Complexity: O(log(N) * 2 * 2 * 11 * 11 * 10) = O(log(N))
 * Space Complexity: O(log(N) * 2 * 2 * 11 * 11) = O(log(N))
 */

var totalWaviness = function (num1, num2) {
  function solve(n) {
    if (n < 0) return 0;

    let sNum = String(n);
    let len = sNum.length;

    let memo = Array(len + 1)
      .fill(0)
      .map(() =>
        Array(2)
          .fill(0)
          .map(() =>
            Array(2)
              .fill(0)
              .map(() =>
                Array(11)
                  .fill(0)
                  .map(() => Array(11).fill(null)),
              ),
          ),
      );

    function dp(idx, tight, started, prevDigitVal, prevPrevDigitVal) {
      if (idx === len) {
        return { totalWaviness: 0, count: 1 };
      }

      let tIdx = tight ? 1 : 0;
      let sIdx = started ? 1 : 0;
      let pIdx = prevDigitVal + 1;
      let ppIdx = prevPrevDigitVal + 1;

      if (memo[idx][tIdx][sIdx][pIdx][ppIdx] !== null) {
        return memo[idx][tIdx][sIdx][pIdx][ppIdx];
      }

      let ansTotalWaviness = 0;
      let ansCount = 0;
      let upperLimit = tight ? parseInt(sNum[idx]) : 9;

      for (let d = 0; d <= upperLimit; d++) {
        let newTight = tight && d === upperLimit;

        let newStarted = started || d > 0;
        let newPrev = newStarted ? d : -1;
        let newPrevPrev = newStarted ? (started ? prevDigitVal : -1) : -1;

        let res = dp(idx + 1, newTight, newStarted, newPrev, newPrevPrev);

        ansTotalWaviness += res.totalWaviness;
        ansCount += res.count;

        if (started && prevPrevDigitVal !== -1) {
          if (
            (prevDigitVal > prevPrevDigitVal && prevDigitVal > d) ||
            (prevDigitVal < prevPrevDigitVal && prevDigitVal < d)
          ) {
            ansTotalWaviness += res.count;
          }
        }
      }

      return (memo[idx][tIdx][sIdx][pIdx][ppIdx] = {
        totalWaviness: ansTotalWaviness,
        count: ansCount,
      });
    }

    return dp(0, true, false, -1, -1).totalWaviness;
  }

  return solve(num2) - solve(num1 - 1);
};
